// These layers deliberately retain dark contrast over photography.
const photographic =
  /\.(auth-editorial|welcome-photos|photo-strip|profile-cover|change-photo|opportunity-cover|save-opportunity)(?![\w])/;
function hexChannels(hex) {
  let value = hex.slice(1);
  if (value.length < 5) value = [...value].map((c) => c + c).join("");
  return [0, 2, 4, 6].map((offset, i) =>
    i === 3 && value.length === 6
      ? 255
      : parseInt(value.slice(offset, offset + 2), 16),
  );
}
function mapColor(hex, prop, selector) {
  const [r, g, b, a] = hexChannels(hex);
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const bright = (r + g + b) / 3;
  const lime = g > r && g > b * 1.5 && g > 150;
  const red = r > g * 1.2 && r > b * 1.2;
  const token = (name) => `var(--studio-${name})`;
  if (/^(color|fill|stroke|text-decoration-color)$/.test(prop)) {
    if (lime) return token("accent-ink");
    if (red && bright > 85) return token("danger");
    if (bright < 90) return hex; // Ink on the retained bright lime buttons.
    return token(bright > 205 ? "ink" : "muted");
  }
  if (/^(border|outline|column-rule)/.test(prop)) {
    return token(lime ? "accent-ink" : red ? "danger" : "line");
  }
  if (/^background/.test(prop)) {
    if (lime) return hex;
    if (red) return "#fff0ee";
    if (a < 240 && max - min < 15 && bright > 230) return "#17211d0a";
    if (max > 200) return hex;
    if (
      selector === scope ||
      /\.(studio-workspace|mobile-app-frame|save-bar)(?![\w-])/.test(selector)
    )
      return token("canvas");
    if (g > r + 4 && g > b + 4) return token("tint");
    return token(bright > 35 ? "subtle" : "panel");
  }
  if (prop === "box-shadow") return "#17211d12";
  if (prop === "scrollbar-color") return token("line");
  return hex;
}

for (const file of files) {
  const tree = postcss.parse(
    fs.readFileSync(path.join(root, `app/espace/studio-${file}.css`), "utf8"),
  );
  tree.walkComments((comment) => comment.remove());
  tree.walkRules((rule) => {
    if (rule.parent.type === "atrule" && /keyframes/.test(rule.parent.name)) {
      rule.remove();
      return;
    }
    rule.selectors = rule.selectors
      .filter((selector) => !photographic.test(selector))
      .map((selector) =>
        selector.includes("body:has(.studio-surface)")
          ? selector.replaceAll("body:has(.studio-surface)", scope)
          : `${scope} ${selector}`,
      );
    if (!rule.selector.trim()) {
      rule.remove();
      return;
    }
    rule.walkDecls((decl) => {
      if (
        !/^(color|background|border|outline|fill|stroke|box-shadow|text-decoration-color|scrollbar-color)/.test(
          decl.prop,
        )
      ) {
        decl.remove();
        return;
      }
      const original = decl.value;
      let value = original.replace(/#[a-f\d]{3,8}\b/gi, (hex) =>
        mapColor(hex, decl.prop, rule.selector),
      );
      if (decl.prop === "color")
        value = value
          .replace(/var\(--primary\)/g, "var(--studio-accent-ink)")
          .replace(/^white$/, "var(--studio-ink)");
      if (value === original) decl.remove();
      else decl.value = value;
    });
    if (!rule.nodes.length) rule.remove();
  });
  tree.walkAtRules((rule) => {
    if (!rule.nodes?.length) rule.remove();
  });
  output.append(tree.nodes);
}
